// package main указывает, что этот файл является главным в программе 
// и его можно запустить как исполняемый проект.
package main

// import подключает стандартные библиотеки (пакеты) языка Go, необходимые для работы.
import (
	"fmt"      // Пакет для форматирования и вывода текста (например, в консоль или браузер).
	"net/http" // Главный пакет для работы с веб-сетью, создания серверов и обработки запросов.
)

// homeHandler — это функция-обработчик для главной страницы сайта (маршрут "/").
// w http.ResponseWriter — это инструмент, через который мы отправляем ответ клиенту (в браузер).
// r *http.Request — это объект, содержащий всю информацию о входящем запросе от клиента.
func homeHandler(w http.ResponseWriter, r *http.Request) {
	
	// Проверяем точный URL-путь запроса. 
	// Так как в Go корень "/" ловит все неизвестные адреса, мы проверяем: если путь НЕ равен "/",
	if r.URL.Path != "/" {
		http.NotFound(w, r) // ...то принудительно возвращаем клиенту стандартную ошибку 404 Not Found.
		return              // Прерываем выполнение функции, чтобы код ниже не выполнялся.
	}
	
	w.WriteHeader(http.StatusOK) // Отправляем клиенту HTTP-статус 200 OK (запрос прошёл успешно).
	
	// Пишем текст ответа прямо в response writer (w), который браузер отобразит на экране.
	fmt.Fprint(w, "Добро пожаловать в приложение Учёт личных трат!")
}

// aboutHandler — функция-обработчик для страницы "О проекте" (маршрут "/about").
func aboutHandler(w http.ResponseWriter, r *http.Request) {
	w.WriteHeader(http.StatusOK) // Отправляем HTTP-статус 200 OK.
	
	// Отправляем текст с описанием задания обратно клиенту.
	fmt.Fprint(w, "Это семестровое практическое задание по веб-разработке на языке Go.")
}

// pingHandler — функция-обработчик для проверки работы сервера (маршрут "/ping").
func pingHandler(w http.ResponseWriter, r *http.Request) {
	
	// Проверяем тип HTTP-метода. Преподаватель требовал, чтобы здесь работал только GET.
	// Если метод запроса НЕ является GET-запросом:
	if r.Method != http.MethodGet {
		// ...то возвращаем ошибку 405 Method Not Allowed (Метод не поддерживается) и выводим текст.
		http.Error(w, "Метод не поддерживается. Используйте только GET.", http.StatusMethodNotAllowed)
		return // Прерываем функцию.
	}
	
	w.WriteHeader(http.StatusOK) // Если это был GET, отправляем статус 200 OK.
	fmt.Fprint(w, "pong")        // Отправляем текстовый ответ "pong".
}

// main — главная точка входа в программу. Именно отсюда начинается выполнение кода при запуске.
func main() {
	
	// Создаем новый маршрутизатор (ServeMux). 
	// Он будет отвечать за прием запросов и распределение их по нужным функциям.
	mux := http.NewServeMux()

	// Регистрируем маршруты в нашем маршрутизаторе:
	mux.HandleFunc("/", homeHandler)       // Если пришли на корень "/", запускаем функцию homeHandler.
	mux.HandleFunc("/about", aboutHandler) // Если пришли на "/about", запускаем aboutHandler.
	mux.HandleFunc("/ping", pingHandler)   // Если пришли на "/ping", запускаем pingHandler.

	// Выводим информационное сообщение в терминал VS Code, чтобы мы знали, что код дошел до этой точки.
	fmt.Println("Сервер запущен на http://localhost:8080")

	// Запускаем веб-сервер на порту 8080 и передаем ему наш настроенный маршрутизатор (mux).
	// Веб-сервер начинает бесконечно слушать входящие запросы.
	err := http.ListenAndServe(":8080", mux)
	
	// Если при запуске сервера произошла критическая ошибка (например, порт 8080 уже занят другой программой):
	if err != nil {
		// ...выводим сообщение об ошибке в консоль.
		fmt.Printf("Ошибка при запуске сервера: %v\n", err)
	}
}
